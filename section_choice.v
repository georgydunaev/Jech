(* 5. CLASSICAL CHOICE STATEMENTS AND CARTESIAN PRODUCT EQUIVALENCE         *)
(* ========================================================================= *)

Definition relational_choice_statement : Prop :=
  forall (A B : Type) (R : A -> B -> Prop),
    (forall x : A, exists y : B, R x y) ->
    exists f : A -> B, forall x : A, R x (f x).

Definition cartesian_product_nonempty_statement : Prop :=
  forall (Idx : Type) (Fam : Idx -> Type),
    (forall i : Idx, exists x : Fam i, True) ->
    exists f : (forall i : Idx, Fam i), True.

Theorem AC_to_cartesian_product :
  relational_choice_statement -> cartesian_product_nonempty_statement.
Proof.
  intros RC Idx Fam H.
  pose (B := { i : Idx & Fam i }).
  pose (R := fun (i : Idx) (b : B) => projT1 b = i).
  assert (Hall : forall i : Idx, exists b : B, R i b).
  { intros i.
    destruct (H i) as [x _].
    exists (existT Fam i x).
    reflexivity.
  }
  destruct (RC Idx B R Hall) as [g Hg].
  assert (Hf : forall i : Idx, Fam i).
  { intros i.
    pose (b := g i).
    assert (Heq : projT1 b = i) by apply (Hg i).
    destruct b as [j x].
    simpl in Heq.
    subst j.
    exact x.
  }
  exists Hf.
  exact I.
Qed.

Theorem cartesian_product_to_AC :
  cartesian_product_nonempty_statement -> relational_choice_statement.
Proof.
  intros CP A B R H.
  pose (Fam := fun x : A => { y : B | R x y }).
  assert (Hnonempty : forall x : A, exists y : Fam x, True).
  { intros x.
    destruct (H x) as [y Hy].
    exists (exist (fun y => R x y) y Hy).
    exact I.
  }
  destruct (CP A Fam Hnonempty) as [f _].
  exists (fun x => proj1_sig (f x)).
  intros x.
  exact (proj2_sig (f x)).
Qed.

Theorem AC_iff_cartesian_product :
  relational_choice_statement <-> cartesian_product_nonempty_statement.
Proof.
  split.
  - apply AC_to_cartesian_product.
  - apply cartesian_product_to_AC.
Qed.

Theorem relational_choice_implies_MSet_choice :
  relational_choice_statement -> AC_MSet_statement.
Proof.
  intros RC X.
  pose (R := fun (A y : MSet) =>
    (In_MSet A X /\ is_nonempty_MSet A -> In_MSet y A) /\
    (~ (In_MSet A X /\ is_nonempty_MSet A) -> y = A)).
  assert (Hall : forall A : MSet, exists y : MSet, R A y).
  { intros A.
    destruct (classic (In_MSet A X /\ is_nonempty_MSet A)) as [Hyes | Hno].
    - destruct Hyes as [Hin [y Hy]].
      exists y. split.
      + intros _. exact Hy.
      + intros Hcontra. exfalso. apply Hcontra. split; [exact Hin | exists y; exact Hy].
    - exists A. split.
      + intros Hcontra. exfalso. apply Hno. exact Hcontra.
      + intros _. reflexivity.
  }
  destruct (RC MSet MSet R Hall) as [f Hf].
  exists f.
  intros A Hin Hne.
  destruct (Hf A) as [Hchoice _].
  apply Hchoice.
  split; assumption.
Qed.

Theorem relational_choice_holds : relational_choice_statement.
Proof.
  exact choice.
Qed.

Theorem cartesian_product_holds : cartesian_product_nonempty_statement.
Proof.
  apply AC_to_cartesian_product.
  exact relational_choice_holds.
Qed.

Theorem MSet_choice_holds : AC_MSet_statement.
Proof.
  apply relational_choice_implies_MSet_choice.
  exact relational_choice_holds.
Qed.

