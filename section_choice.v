Section TukeyDefinitions.

Variable U : Type.

Definition is_finite_subset (F S : U -> Prop) : Prop :=
  (forall x : U, F x -> S x) /\ (exists (l : list U), forall x : U, F x <-> In x l).

Definition is_finite_character (Fam : (U -> Prop) -> Prop) : Prop :=
  forall S : U -> Prop, Fam S <-> (forall F : U -> Prop, is_finite_subset F S -> Fam F).

Definition is_tukey_maximal (Fam : (U -> Prop) -> Prop) (M : U -> Prop) : Prop :=
  Fam M /\ forall S : U -> Prop, Fam S -> (forall x : U, M x -> S x) -> (forall x : U, S x -> M x).

End TukeyDefinitions.

Definition tukey_lemma_statement : Prop :=
  forall (U : Type) (Fam : (U -> Prop) -> Prop),
    (exists S : U -> Prop, Fam S) ->
    is_finite_character U Fam ->
    exists M : U -> Prop, is_tukey_maximal U Fam M.

Axiom tukey_lemma : tukey_lemma_statement.

Theorem tukey_lemma_holds : tukey_lemma_statement.
Proof.
  exact tukey_lemma.
Qed.

