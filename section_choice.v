Section WellOrderingDefinitions.

Variable A : Type.
Variable R : relation A.

Definition is_total : Prop := forall x y : A, R x y \/ R y x.

Definition is_linear_order : Prop := is_partial_order A R /\ is_total.

Definition is_least (S : A -> Prop) (m : A) : Prop :=
  S m /\ forall x : A, S x -> R m x.

Definition is_well_order : Prop :=
  is_linear_order /\ forall S : A -> Prop, (exists x : A, S x) -> exists m : A, is_least S m.

Lemma least_element_unique : forall (S : A -> Prop) (m1 m2 : A),
  is_partial_order A R ->
  is_least S m1 ->
  is_least S m2 ->
  m1 = m2.
Proof.
  intros S m1 m2 [_ [_ Hanti]] [Hin1 Hle1] [Hin2 Hle2].
  apply Hanti.
  - apply Hle1. exact Hin2.
  - apply Hle2. exact Hin1.
Qed.

End WellOrderingDefinitions.

