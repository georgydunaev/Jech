(* 1. PARTIALLY ORDERED SETS, CHAINS, UPPER BOUNDS, AND MAXIMAL ELEMENTS     *)
(* ========================================================================= *)

Section PosetDefinitions.

Variable A : Type.
Variable R : relation A.

Definition is_reflexive : Prop := forall x : A, R x x.

Definition is_transitive_rel : Prop := forall x y z : A, R x y -> R y z -> R x z.

Definition is_antisymmetric : Prop := forall x y : A, R x y -> R y x -> x = y.

Definition is_partial_order : Prop :=
  is_reflexive /\ is_transitive_rel /\ is_antisymmetric.

Definition is_chain (C : A -> Prop) : Prop :=
  forall x y : A, C x -> C y -> R x y \/ R y x.

Definition is_upper_bound (C : A -> Prop) (u : A) : Prop :=
  forall x : A, C x -> R x u.

Definition has_upper_bound (C : A -> Prop) : Prop :=
  exists u : A, is_upper_bound C u.

Definition is_chain_bounded : Prop :=
  forall C : A -> Prop, is_chain C -> has_upper_bound C.

Definition is_maximal (m : A) : Prop :=
  forall x : A, R m x -> x = m.

Definition is_strict_upper_bound (C : A -> Prop) (u : A) : Prop :=
  is_upper_bound C u /\ forall x : A, C x -> x <> u.

Lemma empty_is_chain : is_chain (fun _ => False).
Proof.
  intros x y Hx Hy.
  destruct Hx.
Qed.

Lemma singleton_is_chain : forall x : A,
  is_reflexive -> is_chain (fun y => y = x).
Proof.
  intros x Hrefl y z Hy Hz.
  subst y z.
  left.
  apply Hrefl.
Qed.

Lemma pair_chain_le : forall x y : A,
  is_reflexive -> R x y -> is_chain (fun z => z = x \/ z = y).
Proof.
  intros x y Hrefl Hxy z1 z2 Hz1 Hz2.
  destruct Hz1 as [E1 | E1]; destruct Hz2 as [E2 | E2]; subst.
  - left. apply Hrefl.
  - left. exact Hxy.
  - right. exact Hxy.
  - left. apply Hrefl.
Qed.

End PosetDefinitions.

