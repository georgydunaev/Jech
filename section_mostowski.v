(* 3. ORDINAL RANK FUNCTION                                                  *)
(*                                                                           *)
(*  rank(x) = sup { rank(y) + 1 | y E x }                                    *)
(* ========================================================================= *)

Inductive Ord : Type :=
  | OZero : Ord
  | OSucc : Ord -> Ord
  | OLim : forall (Idx : Type), (Idx -> Ord) -> Ord.

Inductive OLess : Ord -> Ord -> Prop :=
  | OLess_succ : forall o : Ord, OLess o (OSucc o)
  | OLess_lim : forall (Idx : Type) (f : Idx -> Ord) (i : Idx), OLess (f i) (OLim Idx f)
  | OLess_trans : forall o1 o2 o3 : Ord, OLess o1 o2 -> OLess o2 o3 -> OLess o1 o3.

Section RankTheory.

Variable A : Type.
Variable E : relation A.
Variable wf_E : well_founded E.

Fixpoint rank_acc (x : A) (acc : Acc E x) : Ord :=
  match acc with
  | Acc_intro _ f =>
    OLim { y : A | E y x }
      (fun y_sig => OSucc (rank_acc (proj1_sig y_sig) (f (proj1_sig y_sig) (proj2_sig y_sig))))
  end.

Lemma rank_acc_irrel : forall (x : A) (acc1 acc2 : Acc E x),
  rank_acc x acc1 = rank_acc x acc2.
Proof.
  intro x.
  pattern x.
  apply (well_founded_ind wf_E).
  intros x0 IH a1 a2.
  destruct a1 as [f1].
  destruct a2 as [f2].
  simpl.
  f_equal.
  apply functional_extensionality.
  intros [y Hy].
  simpl.
  f_equal.
  apply IH.
  exact Hy.
Qed.

Definition rank (x : A) : Ord := rank_acc x (wf_E x).

Lemma rank_eq_acc : forall (x : A) (acc : Acc E x), rank x = rank_acc x acc.
Proof.
  intros x acc.
  unfold rank.
  apply rank_acc_irrel.
Qed.

Lemma rank_unfold : forall x : A,
  rank x = OLim { y : A | E y x } (fun y_sig => OSucc (rank (proj1_sig y_sig))).
Proof.
  intros x.
  unfold rank at 1.
  destruct (wf_E x) as [f].
  simpl.
  f_equal.
  apply functional_extensionality.
  intros [y Hy].
  simpl.
  f_equal.
  symmetry.
  apply rank_eq_acc.
Qed.

Theorem rank_strictly_increasing : forall x y : A,
  E y x -> OLess (rank y) (rank x).
Proof.
  intros x y H.
  rewrite (rank_unfold x).
  apply OLess_trans with (o2 := OSucc (rank y)).
  - apply OLess_succ.
  - change (OSucc (rank y)) with
      ((fun y_sig : { z : A | E z x } => OSucc (rank (proj1_sig y_sig)))
         (exist (fun z => E z x) y H)).
    apply OLess_lim.
Qed.

End RankTheory.

