(* 4. MOSTOWSKI COLLAPSING THEOREM                                           *)
(*                                                                           *)
(*  pi(x) = { pi(y) | y E x }                                                *)
(* ========================================================================= *)

Inductive MSet : Type :=
  | mset : forall (Idx : Type), (Idx -> MSet) -> MSet.

Definition In_MSet (s t : MSet) : Prop :=
  match t with
  | mset Idx f => exists i : Idx, s = f i
  end.

Definition is_transitive (M : MSet -> Prop) : Prop :=
  forall s t : MSet, M t -> In_MSet s t -> M s.

Section MostowskiTheorem.

Variable A : Type.
Variable E : relation A.
Variable wf_E : well_founded E.

Fixpoint pi_acc (x : A) (acc : Acc E x) : MSet :=
  match acc with
  | Acc_intro _ f =>
    mset { y : A | E y x }
      (fun y_sig => pi_acc (proj1_sig y_sig) (f (proj1_sig y_sig) (proj2_sig y_sig)))
  end.

Lemma pi_acc_irrel : forall (x : A) (acc1 acc2 : Acc E x),
  pi_acc x acc1 = pi_acc x acc2.
Proof.
  intro x.
  pattern x.
  apply (well_founded_ind wf_E).
  intros x0 IH a1 a2.
  destruct a1 as [f1].
  destruct a2 as [f2].
  simpl.
  f_equal.
  apply functional_extensionality.
  intros [y Hy].
  simpl.
  apply IH.
  exact Hy.
Qed.

Definition pi (x : A) : MSet := pi_acc x (wf_E x).

Lemma pi_eq_acc : forall (x : A) (acc : Acc E x), pi x = pi_acc x acc.
Proof.
  intros x acc. unfold pi. apply pi_acc_irrel.
Qed.

Lemma pi_unfold : forall x : A,
  pi x = mset { y : A | E y x } (fun y_sig => pi (proj1_sig y_sig)).
Proof.
  intros x.
  unfold pi at 1.
  destruct (wf_E x) as [f].
  simpl.
  f_equal.
  apply functional_extensionality.
  intros [y Hy].
  simpl.
  symmetry.
  apply pi_eq_acc.
Qed.

Lemma pi_rel_forward : forall x y : A,
  E y x -> In_MSet (pi y) (pi x).
Proof.
  intros x y H.
  rewrite (pi_unfold x).
  simpl.
  exists (exist (fun z => E z x) y H).
  simpl.
  reflexivity.
Qed.

Lemma pi_rel_backward : forall (x : A) (s : MSet),
  In_MSet s (pi x) -> exists y : A, E y x /\ s = pi y.
Proof.
  intros x s Hin.
  rewrite (pi_unfold x) in Hin.
  simpl in Hin.
  destruct Hin as [[y Hy] Heq].
  exists y.
  split; [exact Hy | exact Heq].
Qed.

Definition M_image (s : MSet) : Prop :=
  exists x : A, s = pi x.

Theorem mostowski_transitive : is_transitive M_image.
Proof.
  intros s t [x Ht] Hin.
  subst t.
  apply pi_rel_backward in Hin.
  destruct Hin as [y [Hy Heq]].
  exists y. exact Heq.
Qed.

Theorem mostowski_injective : extensional A E -> forall x y : A,
  pi x = pi y -> x = y.
Proof.
  intros Hext.
  intro x.
  pattern x.
  apply (well_founded_ind wf_E).
  intros x0 IH y Hpi.
  apply Hext.
  intros z.
  split; intros Hz.
  - assert (Hin : In_MSet (pi z) (pi x0)).
    { apply pi_rel_forward. exact Hz. }
    rewrite Hpi in Hin.
    apply pi_rel_backward in Hin.
    destruct Hin as [w [Hw Heqw]].
    assert (Heqzw : z = w).
    { apply (IH z Hz w). exact Heqw. }
    subst w.
    exact Hw.
  - assert (Hin : In_MSet (pi z) (pi y)).
    { apply pi_rel_forward. exact Hz. }
    rewrite <- Hpi in Hin.
    apply pi_rel_backward in Hin.
    destruct Hin as [w [Hw Heqw]].
    assert (Heqwz : w = z).
    { apply (IH w Hw z). symmetry. exact Heqw. }
    subst w.
    exact Hw.
Qed.

Theorem mostowski_isomorphism : extensional A E -> forall x y : A,
  E y x <-> In_MSet (pi y) (pi x).
Proof.
  intros Hext x y.
  split.
  - apply pi_rel_forward.
  - intros Hin.
    apply pi_rel_backward in Hin.
    destruct Hin as [z [Hz Heqz]].
    assert (Heqyz : y = z).
    { apply (mostowski_injective Hext). exact Heqz. }
    subst z.
    exact Hz.
Qed.

Theorem mostowski_uniqueness : forall sigma : A -> MSet,
  (forall x : A, sigma x = mset { y : A | E y x } (fun y_sig => sigma (proj1_sig y_sig))) ->
  forall x : A, sigma x = pi x.
Proof.
  intros sigma Hsigma x.
  pattern x.
  apply (well_founded_ind wf_E).
  intros x0 IH.
  rewrite Hsigma.
  rewrite pi_unfold.
  f_equal.
  apply functional_extensionality.
  intros [y Hy].
  simpl.
  apply IH.
  exact Hy.
Qed.

End MostowskiTheorem.

