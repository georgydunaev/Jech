Definition empty_MSet : MSet := mset False (fun k => match k with end).

Lemma empty_MSet_no_elements : forall s : MSet, ~ In_MSet s empty_MSet.
Proof.
  intros s [k _].
  destruct k.
Qed.

Definition singleton_MSet (s : MSet) : MSet := mset unit (fun _ => s).

Lemma in_singleton_MSet : forall s : MSet, In_MSet s (singleton_MSet s).
