(* 2. TRANSITIVE CLOSURE OF RELATIONS AND ELEMENTS (TC)                     *)
(* ========================================================================= *)

Definition in_TC (x y : A) : Prop := clos_trans A E y x.

Definition TC_set (x y : A) : Prop := y = x \/ in_TC x y.

Lemma TC_step : forall y x : A, E y x -> in_TC x y.
Proof.
  intros y x H.
  apply t_step.
  exact H.
Qed.

Lemma TC_trans : forall z y x : A, in_TC y z -> in_TC x y -> in_TC x z.
Proof.
  intros z y x Hzy Hyx.
  eapply t_trans.
  - exact Hzy.
  - exact Hyx.
Qed.

Lemma TC_is_transitive : forall x y z : A, in_TC x y -> E z y -> in_TC x z.
Proof.
  intros x y z Hxy Hzy.
  eapply t_trans.
  - apply t_step. exact Hzy.
  - exact Hxy.
Qed.

Theorem wf_TC : well_founded E -> well_founded (clos_trans A E).
Proof.
  intro wf_E.
