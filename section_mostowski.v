(* 1. WELL-FOUNDED AND EXTENSIONAL RELATIONS                                 *)
(* ========================================================================= *)

Variable A : Type.
Variable E : relation A.

Definition extensional : Prop :=
  forall x y : A, (forall z : A, E z x <-> E z y) -> x = y.

Definition is_minimal (S : A -> Prop) (m : A) : Prop :=
  S m /\ forall y : A, E y m -> ~ S y.

Theorem well_founded_induction_principle :
  well_founded E ->
  forall P : A -> Prop,
  (forall x : A, (forall y : A, E y x -> P y) -> P x) ->
  forall x : A, P x.
Proof.
  intros wf_E P Hstep x.
  apply (well_founded_ind wf_E P Hstep x).
Qed.

