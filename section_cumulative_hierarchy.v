Theorem In_MSet_wf : well_founded In_MSet.
Proof.
  intros x.
  induction x as [Idx f IH].
  constructor.
  intros y [i Heq].
  subst y.
  apply IH.
Qed.

Theorem no_self_membership : forall x : MSet, ~ In_MSet x x.
Proof.
  intros x H.
  assert (Hacc : Acc In_MSet x) by apply In_MSet_wf.
  induction Hacc as [x0 _ IH].
  apply (IH x0 H H).
Qed.

Theorem no_2_cycle : forall x y : MSet, In_MSet x y -> ~ In_MSet y x.
Proof.
  intros x y Hxy Hyx.
  assert (Hacc : Acc In_MSet x) by apply In_MSet_wf.
  revert y Hxy Hyx.
  induction Hacc as [x0 _ IH].
  intros y Hxy Hyx.
  apply (IH y Hyx x0 Hyx Hxy).
Qed.

Theorem no_3_cycle : forall x y z : MSet, In_MSet x y -> In_MSet y z -> ~ In_MSet z x.
Proof.
  intros x y z Hxy Hyz Hzx.
  assert (Hacc : Acc In_MSet x) by apply In_MSet_wf.
  revert y z Hxy Hyz Hzx.
  induction Hacc as [x0 _ IH].
  intros y z Hxy Hyz Hzx.
  apply (IH z Hzx x0 y Hzx Hxy Hyz).
Qed.

Lemma no_infinite_descent_aux : forall x (f : nat -> MSet),
  Acc In_MSet x -> f 0 = x -> (forall n : nat, In_MSet (f (S n)) (f n)) -> False.
Proof.
  intros x f Hacc.
  revert f.
  induction Hacc as [x0 _ IH].
  intros f Heq Hchain.
  subst x0.
  assert (Hstep : In_MSet (f 1) (f 0)) by apply (Hchain 0).
  apply (IH (f 1) Hstep (fun n => f (S n))).
  - reflexivity.
  - intros n. apply (Hchain (S n)).
Qed.

Theorem no_infinite_descent : forall (f : nat -> MSet),
  ~ (forall n : nat, In_MSet (f (S n)) (f n)).
Proof.
  intros f Hchain.
  apply (no_infinite_descent_aux (f 0) f (In_MSet_wf (f 0)) eq_refl Hchain).
Qed.

Definition is_in_minimal (S : MSet -> Prop) (m : MSet) : Prop :=
