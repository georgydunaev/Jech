(* 6. MONTAGUE-LEVY REFLECTION PRINCIPLE                                     *)
(*                                                                           *)
(*    For any formula phi and any stage V_alpha, there exists a higher       *)
(*    stage V_beta reflecting phi: phi^{V_beta} <-> phi^V.                   *)
(*    Tarski-Vaught criterion: reflection holds under existential witness    *)
(*    closure for subformulas.                                               *)
(* ========================================================================= *)

Definition Reflects (M : MSet -> Prop) (phi : SetFormula) : Prop :=
  forall rho : nat -> MSet, (forall n, M (rho n)) -> (Sat_in M rho phi <-> Sat_V rho phi).

Definition StageReflects (alpha : Ord) (phi : SetFormula) : Prop :=
  Reflects (In_V alpha) phi.

Theorem Delta0_all_stages_reflect : forall (alpha : Ord) (phi : SetFormula),
  is_Delta0 phi -> StageReflects alpha phi.
Proof.
  intros alpha phi Hdelta rho Hrho.
  apply (Delta0_stage_reflection alpha phi Hdelta rho Hrho).
Qed.

Theorem Reflects_Not : forall (M : MSet -> Prop) (p : SetFormula),
  Reflects M p -> Reflects M (FNot p).
Proof.
  intros M p Href rho M_rho.
  simpl.
  rewrite (Href rho M_rho).
  reflexivity.
Qed.

Theorem Reflects_And : forall (M : MSet -> Prop) (p q : SetFormula),
  Reflects M p -> Reflects M q -> Reflects M (FAnd p q).
Proof.
  intros M p q Href1 Href2 rho M_rho.
  simpl.
  rewrite (Href1 rho M_rho).
  rewrite (Href2 rho M_rho).
  reflexivity.
Qed.

Theorem Reflects_Or : forall (M : MSet -> Prop) (p q : SetFormula),
  Reflects M p -> Reflects M q -> Reflects M (FOr p q).
Proof.
  intros M p q Href1 Href2 rho M_rho.
  simpl.
  rewrite (Href1 rho M_rho).
  rewrite (Href2 rho M_rho).
  reflexivity.
Qed.

Theorem Reflects_Imp : forall (M : MSet -> Prop) (p q : SetFormula),
  Reflects M p -> Reflects M q -> Reflects M (FImp p q).
Proof.
  intros M p q Href1 Href2 rho M_rho.
  simpl.
  rewrite (Href1 rho M_rho).
  rewrite (Href2 rho M_rho).
  reflexivity.
Qed.

Definition WitnessClosed (M : MSet -> Prop) (x : nat) (p : SetFormula) : Prop :=
  forall rho : nat -> MSet,
  (forall n, M (rho n)) ->
  (exists v : MSet, Sat_V (update_rho rho x v) p) ->
  (exists v : MSet, M v /\ Sat_V (update_rho rho x v) p).

Theorem Tarski_Vaught_reflection_step_Ex : forall (M : MSet -> Prop) (x : nat) (p : SetFormula),
  (forall s t : MSet, M t -> In_MSet s t -> M s) ->
  Reflects M p ->
  WitnessClosed M x p ->
  Reflects M (FEx x p).
Proof.
  intros M x p Mtrans Href Hwit rho M_rho.
  simpl.
  split.
  - intros [v [Mv Hsat]].
    exists v.
    split; [exact I |].
    apply (Href (update_rho rho x v) (update_rho_preserves_M M rho x v M_rho Mv)).
    exact Hsat.
  - intros [v [_ Hsat]].
    assert (Hwit_sat : exists v0 : MSet, M v0 /\ Sat_V (update_rho rho x v0) p).
    { apply Hwit; [exact M_rho | exists v; exact Hsat]. }
    destruct Hwit_sat as [v0 [Mv0 Hsat0]].
    exists v0.
    split; [exact Mv0 |].
    apply (Href (update_rho rho x v0) (update_rho_preserves_M M rho x v0 M_rho Mv0)).
    exact Hsat0.
Qed.

Definition Montague_Levy_Reflection_Principle : Prop :=
  forall (Phi : list SetFormula) (alpha : Ord),
  exists beta : Ord, OLess alpha beta /\ forall phi, In phi Phi -> StageReflects beta phi.

Theorem cumulative_limit_continuous : forall (Idx : Type) (f : Idx -> Ord) (x : MSet),
  In_V (OLim Idx f) x <-> (exists i : Idx, In_V (f i) x).
