(* 2. TRANSITIVITY AND MONOTONICITY OF CUMULATIVE STAGES                     *)
(*                                                                           *)
(*    V_alpha is transitive: x in V_alpha /\ y in x implies y in V_alpha     *)
(*    Monotonicity: alpha <= beta implies V_alpha subset V_beta              *)
(* ========================================================================= *)

Definition stage_transitive (alpha : Ord) : Prop :=
  forall x y : MSet, In_V alpha x -> In_MSet y x -> In_V alpha y.

Definition stage_succ_monotone (alpha : Ord) : Prop :=
  forall x : MSet, In_V alpha x -> In_V (OSucc alpha) x.

Lemma stage_transitive_lim : forall (Idx : Type) (f : Idx -> Ord),
  (forall i : Idx, stage_transitive (f i)) ->
  stage_transitive (OLim Idx f).
Proof.
  intros Idx f IH x y Hx Hy.
  apply V_lim_union in Hx.
  destruct Hx as [i Hx].
  apply V_lim_union.
  exists i.
  apply (IH i x y Hx Hy).
Qed.

Theorem stage_trans_and_succ_mono : forall alpha : Ord,
  stage_transitive alpha /\ stage_succ_monotone alpha.
Proof.
  induction alpha as [ | a [IHa_trans IHa_mono] | Idx f IHf ].
  - split.
    + intros x y H. inversion H.
    + intros x H. inversion H.
  - assert (Htrans : stage_transitive (OSucc a)).
    { intros x y Hx Hy.
      inversion Hx as [alpha0 x0 Hsub | ]; subst.
      apply IHa_mono.
      apply Hsub. exact Hy. }
    split.
    + exact Htrans.
    + intros x Hx.
      apply In_V_succ.
      intros y Hy.
      apply Htrans with (x := x); [exact Hx | exact Hy].
  - assert (Htrans : stage_transitive (OLim Idx f)).
    { apply stage_transitive_lim.
      intros i. apply (proj1 (IHf i)). }
    split.
    + exact Htrans.
    + intros x Hx.
      apply In_V_succ.
      intros y Hy.
      apply Htrans with (x := x); [exact Hx | exact Hy].
Qed.

Corollary V_alpha_transitive : forall alpha : Ord, stage_transitive alpha.
Proof.
  intro alpha.
  apply (proj1 (stage_trans_and_succ_mono alpha)).
Qed.

Lemma V_monotonic_less : forall a b : Ord,
  OLess a b -> forall x : MSet, In_V a x -> In_V b x.
Proof.
  intros a b Hless.
  induction Hless as [ o | Idx f i | o1 o2 o3 H12 IH12 H23 IH23 ].
  - intros x Hx.
    apply (proj2 (stage_trans_and_succ_mono o)).
    exact Hx.
  - intros x Hx.
    apply (In_V_lim Idx f x i Hx).
  - intros x Hx.
    apply IH23.
    apply IH12.
    exact Hx.
Qed.

Definition OLe (a b : Ord) : Prop := a = b \/ OLess a b.

Theorem V_monotonic : forall a b : Ord,
  OLe a b -> forall x : MSet, In_V a x -> In_V b x.
Proof.
  intros a b [Heq | Hless] x Hx.
  - subst b. exact Hx.
  - apply (V_monotonic_less a b Hless x Hx).
Qed.

