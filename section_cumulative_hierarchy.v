(* 1. STAGES OF THE CUMULATIVE HIERARCHY                                     *)
(*                                                                           *)
(*    V_0 = empty                                                            *)
(*    V_{alpha+1} = Power(V_alpha)                                           *)
(*    V_lambda = Union_{beta < lambda} V_beta                                *)
(* ========================================================================= *)

Inductive In_V : Ord -> MSet -> Prop :=
  | In_V_succ : forall (alpha : Ord) (x : MSet),
      (forall y : MSet, In_MSet y x -> In_V alpha y) ->
      In_V (OSucc alpha) x
  | In_V_lim : forall (Idx : Type) (f : Idx -> Ord) (x : MSet) (i : Idx),
      In_V (f i) x ->
      In_V (OLim Idx f) x.

Definition stage (alpha : Ord) : MSet -> Prop := In_V alpha.

Lemma In_V_zero_empty : forall x : MSet, ~ In_V OZero x.
Proof.
  intros x H.
  inversion H.
Qed.

Lemma empty_in_V_succ : forall alpha : Ord, In_V (OSucc alpha) empty_MSet.
Proof.
  intro alpha.
  apply In_V_succ.
  intros y Hy.
  apply empty_MSet_no_elements in Hy.
  destruct Hy.
Qed.

Definition V_0_is_empty : Prop := forall x : MSet, ~ In_V OZero x.

Theorem V_0_empty : V_0_is_empty.
Proof.
  exact In_V_zero_empty.
Qed.

Lemma V_succ_power : forall (alpha : Ord) (x : MSet),
  In_V (OSucc alpha) x <-> (forall y : MSet, In_MSet y x -> In_V alpha y).
Proof.
  intros alpha x.
  split.
  - intros H y Hy.
    inversion H as [alpha0 x0 Hsub | ]; subst.
    apply Hsub. exact Hy.
  - intros H.
    apply In_V_succ.
    exact H.
Qed.

Lemma V_lim_union : forall (Idx : Type) (f : Idx -> Ord) (x : MSet),
  In_V (OLim Idx f) x <-> (exists i : Idx, In_V (f i) x).
Proof.
  intros Idx f x.
  split.
  - intro H.
    dependent destruction H.
    exists i. exact H.
  - intros [i H].
    apply (In_V_lim Idx f x i H).
Qed.

