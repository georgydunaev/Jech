(* 5. FIRST-ORDER SET FORMULAS AND DELTA_0 ABSOLUTENESS                      *)
(*                                                                           *)
(*    Bounded formulas (Delta_0) are absolute between any transitive         *)
(*    structures, and thus reflect to every cumulative stage V_alpha.        *)
(* ========================================================================= *)

Inductive SetFormula : Type :=
  | AtomEq : nat -> nat -> SetFormula
  | AtomIn : nat -> nat -> SetFormula
  | FNot : SetFormula -> SetFormula
  | FAnd : SetFormula -> SetFormula -> SetFormula
  | FOr : SetFormula -> SetFormula -> SetFormula
  | FImp : SetFormula -> SetFormula -> SetFormula
  | FBoundedAll : nat -> nat -> SetFormula -> SetFormula
  | FBoundedEx : nat -> nat -> SetFormula -> SetFormula
  | FAll : nat -> SetFormula -> SetFormula
  | FEx : nat -> SetFormula -> SetFormula.

Inductive is_Delta0 : SetFormula -> Prop :=
  | Delta0_Eq : forall x y, is_Delta0 (AtomEq x y)
  | Delta0_In : forall x y, is_Delta0 (AtomIn x y)
  | Delta0_Not : forall p, is_Delta0 p -> is_Delta0 (FNot p)
  | Delta0_And : forall p q, is_Delta0 p -> is_Delta0 q -> is_Delta0 (FAnd p q)
  | Delta0_Or : forall p q, is_Delta0 p -> is_Delta0 q -> is_Delta0 (FOr p q)
  | Delta0_Imp : forall p q, is_Delta0 p -> is_Delta0 q -> is_Delta0 (FImp p q)
  | Delta0_BAll : forall x y p, is_Delta0 p -> is_Delta0 (FBoundedAll x y p)
  | Delta0_BEx : forall x y p, is_Delta0 p -> is_Delta0 (FBoundedEx x y p).

Definition update_rho (rho : nat -> MSet) (x : nat) (v : MSet) : nat -> MSet :=
  fun y => if Nat.eqb x y then v else rho y.

Fixpoint Sat_in (M : MSet -> Prop) (rho : nat -> MSet) (phi : SetFormula) : Prop :=
  match phi with
  | AtomEq x y => rho x = rho y
  | AtomIn x y => In_MSet (rho x) (rho y)
  | FNot p => ~ Sat_in M rho p
  | FAnd p q => Sat_in M rho p /\ Sat_in M rho q
  | FOr p q => Sat_in M rho p \/ Sat_in M rho q
  | FImp p q => Sat_in M rho p -> Sat_in M rho q
  | FBoundedAll x y p => forall v : MSet, In_MSet v (rho y) -> Sat_in M (update_rho rho x v) p
  | FBoundedEx x y p => exists v : MSet, In_MSet v (rho y) /\ Sat_in M (update_rho rho x v) p
  | FAll x p => forall v : MSet, M v -> Sat_in M (update_rho rho x v) p
  | FEx x p => exists v : MSet, M v /\ Sat_in M (update_rho rho x v) p
  end.

Definition Sat_V (rho : nat -> MSet) (phi : SetFormula) : Prop :=
  Sat_in (fun _ => True) rho phi.

Definition Sat_V_stage (alpha : Ord) (rho : nat -> MSet) (phi : SetFormula) : Prop :=
  Sat_in (In_V alpha) rho phi.

Lemma update_rho_preserves_M : forall (M : MSet -> Prop) (rho : nat -> MSet) (x : nat) (v : MSet),
  (forall n, M (rho n)) -> M v -> forall n, M (update_rho rho x v n).
Proof.
  intros M rho x v Hrho Hv n.
  unfold update_rho.
  destruct (Nat.eqb x n) eqn:Heq.
  - exact Hv.
  - apply Hrho.
Qed.

Theorem Delta0_absoluteness : forall (phi : SetFormula),
  is_Delta0 phi ->
  forall (M N : MSet -> Prop),
  (forall s t : MSet, M t -> In_MSet s t -> M s) ->
  (forall s t : MSet, N t -> In_MSet s t -> N s) ->
  forall rho : nat -> MSet,
  (forall n, M (rho n)) ->
  (forall n, N (rho n)) ->
  (Sat_in M rho phi <-> Sat_in N rho phi).
Proof.
  intros phi Hdelta.
  induction Hdelta; intros M N Mtrans Ntrans rho M_rho N_rho; simpl.
  - reflexivity.
  - reflexivity.
  - split; intros Hneg Hsat; apply Hneg.
    + apply (IHHdelta N M Ntrans Mtrans rho N_rho M_rho). exact Hsat.
    + apply (IHHdelta M N Mtrans Ntrans rho M_rho N_rho). exact Hsat.
  - split; intros [H1 H2]; split.
    + apply (IHHdelta1 M N Mtrans Ntrans rho M_rho N_rho). exact H1.
    + apply (IHHdelta2 M N Mtrans Ntrans rho M_rho N_rho). exact H2.
    + apply (IHHdelta1 N M Ntrans Mtrans rho N_rho M_rho). exact H1.
    + apply (IHHdelta2 N M Ntrans Mtrans rho N_rho M_rho). exact H2.
  - split; intros [H1 | H2].
    + left. apply (IHHdelta1 M N Mtrans Ntrans rho M_rho N_rho). exact H1.
    + right. apply (IHHdelta2 M N Mtrans Ntrans rho M_rho N_rho). exact H2.
    + left. apply (IHHdelta1 N M Ntrans Mtrans rho N_rho M_rho). exact H1.
    + right. apply (IHHdelta2 N M Ntrans Mtrans rho N_rho M_rho). exact H2.
  - split; intros Himp Hsat.
    + apply (IHHdelta2 M N Mtrans Ntrans rho M_rho N_rho).
      apply Himp.
      apply (IHHdelta1 N M Ntrans Mtrans rho N_rho M_rho). exact Hsat.
    + apply (IHHdelta2 N M Ntrans Mtrans rho N_rho M_rho).
      apply Himp.
      apply (IHHdelta1 M N Mtrans Ntrans rho M_rho N_rho). exact Hsat.
  - split; intros Hall v Hvin.
    + assert (Mv : M v) by (apply (Mtrans v (rho y)); [apply M_rho | exact Hvin]).
      assert (Nv : N v) by (apply (Ntrans v (rho y)); [apply N_rho | exact Hvin]).
      apply (IHHdelta M N Mtrans Ntrans (update_rho rho x v)
               (update_rho_preserves_M M rho x v M_rho Mv)
               (update_rho_preserves_M N rho x v N_rho Nv)).
      apply Hall. exact Hvin.
    + assert (Mv : M v) by (apply (Mtrans v (rho y)); [apply M_rho | exact Hvin]).
      assert (Nv : N v) by (apply (Ntrans v (rho y)); [apply N_rho | exact Hvin]).
      apply (IHHdelta M N Mtrans Ntrans (update_rho rho x v)
               (update_rho_preserves_M M rho x v M_rho Mv)
               (update_rho_preserves_M N rho x v N_rho Nv)).
      apply Hall. exact Hvin.
  - split; intros [v [Hvin Hsat]].
    + assert (Mv : M v) by (apply (Mtrans v (rho y)); [apply M_rho | exact Hvin]).
      assert (Nv : N v) by (apply (Ntrans v (rho y)); [apply N_rho | exact Hvin]).
      exists v. split; [exact Hvin |].
      apply (IHHdelta M N Mtrans Ntrans (update_rho rho x v)
               (update_rho_preserves_M M rho x v M_rho Mv)
               (update_rho_preserves_M N rho x v N_rho Nv)).
      exact Hsat.
    + assert (Mv : M v) by (apply (Mtrans v (rho y)); [apply M_rho | exact Hvin]).
      assert (Nv : N v) by (apply (Ntrans v (rho y)); [apply N_rho | exact Hvin]).
      exists v. split; [exact Hvin |].
      apply (IHHdelta M N Mtrans Ntrans (update_rho rho x v)
               (update_rho_preserves_M M rho x v M_rho Mv)
               (update_rho_preserves_M N rho x v N_rho Nv)).
      exact Hsat.
Qed.

Lemma V_transitive_all : forall s t : MSet, (fun _ => True) t -> In_MSet s t -> (fun _ => True) s.
Proof.
  intros s t _ _. exact I.
Qed.

Corollary Delta0_stage_reflection : forall (alpha : Ord) (phi : SetFormula),
  is_Delta0 phi ->
  forall rho : nat -> MSet,
  (forall n, In_V alpha (rho n)) ->
  (Sat_V_stage alpha rho phi <-> Sat_V rho phi).
Proof.
  intros alpha phi Hdelta rho Hrho.
  unfold Sat_V_stage, Sat_V.
  apply (Delta0_absoluteness phi Hdelta (In_V alpha) (fun _ => True)).
  - intros s t Ht Hst. apply (V_alpha_transitive alpha t s Ht Hst).
  - apply V_transitive_all.
  - exact Hrho.
  - intros n. exact I.
Qed.

